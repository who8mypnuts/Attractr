"""Generate docs/attractors/*.md (one page per attractor) + an index, with thumbnails.

Usage: python tools/gen_attractor_docs.py [--thumbs] [--engine cpu]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from attractr.core.attractors.registry import registry
from attractr.core.io.image_export import to_pil
from attractr.core.render.pipeline import default_settings, render
from attractr.core.render.settings import Quality

OUT = Path("docs/attractors")


def page(spec, thumb_rel: str | None) -> str:
    lines = [f"# {spec.name}", "", f"`{spec.id}` · {spec.kind} · {spec.dims}-D · family: {spec.family}", ""]
    if thumb_rel:
        lines += [f"![{spec.name}]({thumb_rel})", ""]
    if spec.description:
        lines += [spec.description, ""]
    lines += ["## Equations", "", "```text", *spec.formula_text(), "```", ""]
    if spec.params:
        lines += ["## Parameters", "", "| Name | Default | Range | Meaning |", "|---|---|---|---|"]
        lines += [f"| {p.name} | {p.default:g} | [{p.lo:g}, {p.hi:g}] | {p.hint} |" for p in spec.params]
        lines.append("")
    if spec.is_flow:
        lines += [f"Integration: RK4, default dt = {spec.dt:g}, initial condition {spec.ic}.", ""]
    if spec.references:
        lines += ["## References", ""] + [f"- {r}" for r in spec.references] + [""]
    lines += ["## Source (`.atr`)", "", "```text", spec.source.rstrip(), "```", ""]
    lines += [f"Render it: `attractr render {spec.id} --size 2048x2048 --report md`", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--thumbs", action="store_true", help="render 256² thumbnails")
    ap.add_argument("--engine", default="auto")
    a = ap.parse_args()
    registry.load()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "images").mkdir(exist_ok=True)
    index = ["# Built-in attractors", "", f"{len(registry.ids())} systems. Generated by `tools/gen_attractor_docs.py`.", ""]
    fam = None
    for spec in registry.all():
        if spec.family != fam:
            fam = spec.family
            index += [f"## {fam}", ""]
        thumb_rel = None
        if a.thumbs:
            s = default_settings(spec, Quality(width=256, height=256, points_per_pixel=6))
            try:
                _, dev = render(s, engine=a.engine)
                to_pil(dev).save(OUT / "images" / f"{spec.id}.png")
                thumb_rel = f"images/{spec.id}.png"
            except Exception as exc:  # noqa: BLE001
                print("thumb failed", spec.id, exc)
        elif (OUT / "images" / f"{spec.id}.png").exists():
            thumb_rel = f"images/{spec.id}.png"
        (OUT / f"{spec.id}.md").write_text(page(spec, thumb_rel), encoding="utf-8")
        index.append(f"- [{spec.name}]({spec.id}.md) — {spec.kind}, {spec.dims}-D, {len(spec.params)} params")
        print("wrote", spec.id)
    (OUT / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
