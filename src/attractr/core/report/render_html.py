"""Report → self-contained HTML (also the input for the PDF renderer)."""

from __future__ import annotations

import html

from attractr.core.report.model import Report, Table

CSS = """
body{font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;background:#0e0e14;color:#e6e6ee;max-width:960px;margin:2em auto;padding:0 1.5em;line-height:1.45}
h1{color:#4fc3f7;border-bottom:1px solid #2a2a3a;padding-bottom:.3em} h2{color:#b39ddb;margin-top:1.6em}
table{border-collapse:collapse;width:100%;margin:.6em 0;font-size:.92em} th,td{border:1px solid #2a2a3a;padding:.35em .6em;text-align:left;vertical-align:top}
th{background:#181826;color:#9fd8ff} tr:nth-child(even) td{background:#121220}
pre,code{background:#161622;color:#c8e6ff;border-radius:6px} pre{padding:.8em;overflow:auto;word-break:break-all;white-space:pre-wrap}
img{max-width:100%;border-radius:8px;border:1px solid #2a2a3a} .sub{color:#888;font-style:italic} .foot{color:#666;font-size:.85em;margin-top:3em}
"""


def table_html(t: Table) -> str:
    h = "".join(f"<th>{html.escape(str(c))}</th>" for c in t.headers)
    rows = "".join("<tr>" + "".join(f"<td>{html.escape(str(c))}</td>" for c in r) + "</tr>" for r in t.rows)
    return f"<table><thead><tr>{h}</tr></thead><tbody>{rows}</tbody></table>"


def render_html(r: Report, inline_css: bool = True) -> str:
    parts = ["<!doctype html><html><head><meta charset='utf-8'>", f"<title>{html.escape(r.title)}</title>"]
    if inline_css:
        parts.append(f"<style>{CSS}</style>")
    parts += ["</head><body>", f"<h1>{html.escape(r.title)}</h1>", f"<p class='sub'>{html.escape(r.subtitle)}</p>"]
    if r.thumbnail:
        parts.append(f"<p><img src='{html.escape(r.thumbnail)}' alt='render'></p>")
    for s in r.sections:
        parts.append(f"<h2>{html.escape(s.title)}</h2>")
        parts += [f"<p>{html.escape(p)}</p>" for p in s.paragraphs]
        if s.code:
            parts.append(f"<pre><code>{html.escape(s.code)}</code></pre>")
        parts += [table_html(t) for t in s.tables]
        if s.image:
            parts.append(f"<p><img src='{html.escape(s.image)}' alt='{html.escape(s.title)}'></p>")
        if s.bullets:
            parts.append("<ul>" + "".join(f"<li>{html.escape(b)}</li>" for b in s.bullets) + "</ul>")
    parts.append(f"<p class='foot'>Generated by Attractr on {r.generated:%Y-%m-%d %H:%M:%S}</p></body></html>")
    return "\n".join(parts)
