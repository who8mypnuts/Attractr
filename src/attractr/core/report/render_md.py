"""Report → Markdown."""

from __future__ import annotations

from attractr.core.report.model import Report, Table


def table_md(t: Table) -> str:
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    lines = ["| " + " | ".join(esc(h) for h in t.headers) + " |", "|" + "---|" * len(t.headers)]
    lines += ["| " + " | ".join(esc(c) for c in r) + " |" for r in t.rows]
    return "\n".join(lines)


def render_markdown(r: Report) -> str:
    out = [f"# {r.title}", "", f"_{r.subtitle}_", ""]
    if r.thumbnail:
        out += [f"![render]({r.thumbnail})", ""]
    for s in r.sections:
        out += [f"## {s.title}", ""]
        for p in s.paragraphs:
            out += [p, ""]
        if s.code:
            out += [f"```{s.code_lang}", s.code, "```", ""]
        for t in s.tables:
            out += [table_md(t), ""]
        if s.image:
            out += [f"![{s.title}]({s.image})", ""]
        for b in s.bullets:
            out.append(f"- {b}")
        if s.bullets:
            out.append("")
    out.append(f"_Generated by Attractr on {r.generated:%Y-%m-%d %H:%M:%S}_")
    return "\n".join(out) + "\n"
