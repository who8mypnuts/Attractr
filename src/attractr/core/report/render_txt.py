"""Report → plain text (fixed-width tables)."""

from __future__ import annotations

from attractr.core.report.model import Report, Table


def table_txt(t: Table) -> str:
    rows = [t.headers] + [[str(c).replace("\n", " ") for c in r] for r in t.rows]
    widths = [min(60, max(len(r[i]) for r in rows)) for i in range(len(t.headers))]
    fmt = lambda r: "  ".join(c[: widths[i]].ljust(widths[i]) for i, c in enumerate(r))  # noqa: E731
    lines = [fmt(rows[0]), "  ".join("-" * w for w in widths)] + [fmt(r) for r in rows[1:]]
    return "\n".join(lines)


def render_text(r: Report) -> str:
    bar = "=" * len(r.title)
    out = [r.title, bar, r.subtitle, ""]
    for s in r.sections:
        out += [s.title, "-" * len(s.title)]
        out += s.paragraphs
        if s.code:
            out += ["    " + line for line in s.code.splitlines()]
        for t in s.tables:
            out += [table_txt(t), ""]
        out += [f"  * {b}" for b in s.bullets]
        out.append("")
    out.append(f"Generated by Attractr on {r.generated:%Y-%m-%d %H:%M:%S}")
    return "\n".join(out) + "\n"
